#define LED_G_1		P35

///***********************************************************************************
//Function:   	void INT_T0(void)
//Description:	T0 Interrupt handler
//Input:   
//Output:     
//*************************************************************************************/
void INT_T0(void) interrupt INT_VECTOR_T0
{

	LED_G_0=!LED_G_0;								// TF0 auto clear by HW
}

///***********************************************************************************
//Function:   	void INT_T1(void)
//Description:	T1 Interrupt handler
//Input:   
//Output:     
//*************************************************************************************/
void INT_T1(void) interrupt INT_VECTOR_T1
{
	LED_R=!LED_R;									//TF1 auto clear by HW
}

///***********************************************************************************
//Function:   	void INT_T2(void)
//Description:	T2 Interrupt handler
//Input:   
//Output:     
//*************************************************************************************/
void INT_T2(void) interrupt INT_VECTOR_T2
{
	_push_(SFRPI);
	SFRPI=0;										// TF2,EXF2 only Page-0
	if(TF2)
	{
		LED_G_1=!LED_G_1;
		TF2=0;
	}
	_pop_(SFRPI);
}

///***********************************************************************************
//Function:   	void INT_T0(void)
//Description:	T3 Interrupt handler
//Input:   
//Output:     
//*************************************************************************************/
void INT_T3(void) interrupt INT_VECTOR_T3
{
	_push_(SFRPI);
	SFRPI=1;										// TF3,EXF3 only Page 1
	if(TF3)						
	{
		P30=!P30;
		TF3=0;
	}
	_pop_(SFRPI);				
}

