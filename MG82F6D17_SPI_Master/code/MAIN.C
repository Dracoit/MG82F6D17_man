///***********************************************************************************
//Function:       void InitSystem(void)
//Description:    Initialize MCU
//Input:   
//Output:     
//*************************************************************************************/
void InitSystem(void)
{
	InitPort();
	InitClock();
	InitSPI();
}


void main()
{
	u8 x,y;
	
    InitSystem();
	
	LED_G_1=0;LED_R=0;
	DelayXms(1000);
	LED_G_1=1;LED_R=1;

	x++;
	
    while(1)
    {
		DelayXms(50);
		LED_G_1 = !LED_G_1;

		LED_R=1;
		SPI_nSS=0;				
		y=SPITransceiver(x);
		SPI_nSS=1;
		if(x!=y) LED_R=0;
		x++;
    }
}


